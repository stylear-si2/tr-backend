ALTER TABLE suscripcion_stripe
    ADD COLUMN usuario_pagador_id BIGINT;

CREATE TABLE comprobante_pago_envio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id) ON DELETE CASCADE,
    clave TEXT NOT NULL,
    clave_resend UUID NOT NULL DEFAULT gen_random_uuid(),
    destinatario TEXT,
    datos JSONB NOT NULL,
    pdf BYTEA,
    estado TEXT NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO')),
    intentos INTEGER NOT NULL DEFAULT 0,
    primer_intento TIMESTAMPTZ,
    proximo_intento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviado_en TIMESTAMPTZ,
    UNIQUE (empresa_id, clave)
);

CREATE INDEX idx_comprobante_pago_pendiente
    ON comprobante_pago_envio (proximo_intento, id)
    WHERE estado = 'PENDIENTE';
